def family(name, fill, hover, active, on, soft, ink=None):
    t = {name: fill, f"{name}-hover": hover, f"{name}-active": active, f"on-{name}": on, f"{name}-soft": soft}
    return t | ({f"{name}-ink": ink} if ink else {})


